import { chromium } from "playwright-core";
import fs from "node:fs";
const svg = fs.readFileSync("L:/naqsh/assets/mascot/naqsh.svg", "utf8");
const browser = await chromium.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: true });
const page = await browser.newPage({ viewport: { width: 32, height: 32 }, deviceScaleFactor: 1 });
await page.setContent(`<style>html,body{margin:0;background:transparent}svg{width:32px;height:32px;display:block}</style>${svg}`);
await page.waitForTimeout(150);
await page.screenshot({ path: "L:/naqsh-review/mascot-assets/brand/favicon-32.png", omitBackground: true });
await browser.close();
console.log("favicon written");
